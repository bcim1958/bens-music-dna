// Derive membership only from explicit playlist relations, never genre/style fields.
const fs = require('node:fs'), path = require('node:path'), zlib = require('node:zlib'), vm = require('node:vm');
const root = path.join(__dirname, '..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
const context = {window: {}};
vm.runInNewContext(read('test/music-dna-relation-registry-v1.js'), context);
const worlds = context.window.MUSIC_DNA_RELATION_REGISTRY_V1.genreDnaTaxonomy.groups.flatMap(g => g.worlds);
const memberships = Object.fromEntries(worlds.map(w => [w, []]));
const unmatchedPlaylists = new Set();
let count = 0;
for (let part = 1; part <= 16; part++) {
  const file = `data/surprise-prod-full-${String(part).padStart(2, '0')}.txt`;
  const payload = JSON.parse(zlib.gunzipSync(Buffer.from(read(file).replace(/\s/g, ''), 'base64')));
  if (payload.p !== part || payload.n !== 16 || payload.total !== 3284) throw Error('Invalid master part: ' + file);
  count += payload.a.length;
  payload.a.forEach((row, index) => {
    for (const playlist of row[7] || []) {
      if (!memberships[playlist]) { unmatchedPlaylists.add(playlist); continue; }
      memberships[playlist].push({artist: row[0], source: file, row: index + 1, playlist});
    }
  });
}
if (count !== 3284) throw Error('Incomplete master snapshot');
// Explicit title reconciliation for the two confirmed playlists; no fuzzy matching.
for (const [file, world] of [
  ['docs/CHECKPOINT-2026-09-09-UK-PUNK-01-RAW-REBELLIOUS.md', 'UK Punk; Raw and Rebellious DNA'],
  ['docs/CHECKPOINT-2026-09-09-UK-PUNK-02-ART-HOOKS-ATTITUDE.md', 'UK Punk; Art, Hooks and Attitude DNA']
]) {
  const rows = [...read(file).matchAll(/^(\d+)\. (.+?) — (.+?) — `(spotify:track:[A-Za-z0-9]+)`/gm)];
  if (rows.length !== 30) throw Error('Incomplete confirmed playlist: ' + file);
  memberships[world] = rows.map(m => ({artist: m[2], source: file, row: Number(m[1]), playlist: world, trackUri: m[4]}));
}
const data = {version: 1, sourceSnapshot: 'Master 1.8 2026-09-04 v2 production export; UK Punk 2026-09-09 confirmed checkpoints', unmatchedPlaylists: [...unmatchedPlaylists].sort(), memberships};
const output = '// Generated by scripts/build-genre-dna-memberships.cjs; do not edit.\nwindow.MUSIC_DNA_GENRE_MEMBERSHIPS_V1 = ' + JSON.stringify(data, null, 2) + ';\n';
const target = 'test/music-dna-genre-memberships-v1.js';
if (process.argv.includes('--check')) { if (read(target) !== output) throw Error('Stale membership payload'); }
else fs.writeFileSync(path.join(root, target), output);
console.log(`Verified ${count} master artists; ${Object.values(memberships).filter(a => a.length).length}/42 worlds have explicit playlist evidence.`);
